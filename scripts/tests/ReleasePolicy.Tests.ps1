Invoke-Case 'manual and tag releases share a version group without cancelling publication' {
    $release = Get-Content -LiteralPath (Join-Path $sourceRoot '.github/workflows/release.yml') -Raw
    Assert-True ($release.Contains("format('v{0}', inputs.version)")) 'Manual and tag release concurrency must normalize to v-prefixed versions.'
    Assert-True ($release.Contains('cancel-in-progress: false')) 'Release work must never cancel running publication.'
}

function Invoke-ReleaseNotesStep([string]$Fixture, [string]$Tag, [string]$RunnerTemp) {
    $workflow = Get-Content -LiteralPath (Join-Path $sourceRoot '.github/workflows/release.yml') -Raw
    # Execute only the assembly step from the real workflow; never any publication commands.
    $step = [regex]::Match($workflow,
        '(?m)^      - name: Prepend curated release notes when available\r?\n        shell: pwsh\r?\n        run: \|\r?\n(?<script>(?:          .*\r?\n)+)')
    Assert-True $step.Success 'The curated-notes assembly step must exist as a standalone PowerShell step.'
    $scriptText = [regex]::Replace($step.Groups['script'].Value, '(?m)^          ', '')
    $savedTag = $env:RELEASE_TAG
    $savedRunnerTemp = $env:RUNNER_TEMP
    Push-Location -LiteralPath $Fixture
    try {
        $env:RELEASE_TAG = $Tag
        $env:RUNNER_TEMP = $RunnerTemp
        & ([scriptblock]::Create($scriptText))
    }
    finally {
        $env:RELEASE_TAG = $savedTag
        $env:RUNNER_TEMP = $savedRunnerTemp
        Pop-Location
    }
}

Invoke-Case 'release body prepends only the matching curated notes and preserves the changelog' {
    $fixture = New-Fixture
    $notesRoot = Join-Path $fixture 'docs/release-notes'
    $runnerTemp = Join-Path $fixture 'runner temp'
    New-Item -ItemType Directory -Path $notesRoot, $runnerTemp | Out-Null
    $generatedPath = Join-Path $runnerTemp 'release-notes.md'
    $curated = "# Highlights — Ghost of Yōtei`r`n`r`nKeep backups.`r`n"
    $changelog = "## 0.1.0-rc.2`n`n### Fixes`n- Exact generated text (abc1234)`n"
    [IO.File]::WriteAllText((Join-Path $notesRoot 'v0.1.0-rc.2.md'), $curated)
    [IO.File]::WriteAllText((Join-Path $notesRoot 'v0.1.0-rc.1.md'), 'Wrong release')
    [IO.File]::WriteAllText($generatedPath, $changelog)

    Invoke-ReleaseNotesStep $fixture 'v0.1.0-rc.2' $runnerTemp

    $actual = [IO.File]::ReadAllText($generatedPath)
    Assert-True ($actual -ceq "$($curated.TrimEnd())`n`n$changelog") 'Curated UTF-8 highlights must precede the entire unchanged changelog with a blank line.'
    $bytes = [IO.File]::ReadAllBytes($generatedPath)
    Assert-True ($bytes[0] -eq [byte][char]'#') 'The assembled UTF-8 notes must not start with a BOM.'
    $workflow = Get-Content -LiteralPath (Join-Path $sourceRoot '.github/workflows/release.yml') -Raw
    $generate = $workflow.IndexOf('- name: Generate conventional commit changelog')
    $prepend = $workflow.IndexOf('- name: Prepend curated release notes when available')
    $publish = $workflow.IndexOf('- name: Verify assets and publish release')
    Assert-True ($generate -ge 0 -and $generate -lt $prepend -and $prepend -lt $publish) 'Assemble notes after git-cliff and before draft creation/publication.'
    Assert-True ($workflow.Contains('--output ${{ runner.temp }}/release-notes.md')) 'git-cliff must write the file used by assembly.'
    $notesArguments = [regex]::Matches($workflow, "--notes-file '\$\{\{ runner.temp \}\}/release-notes.md'")
    Assert-True ($notesArguments.Count -eq 2) 'Draft creation and final publication must both use the assembled notes.'

    [IO.File]::WriteAllText((Join-Path $notesRoot 'v0.1.0-rc.2.md'), '')
    [IO.File]::WriteAllText($generatedPath, $changelog)
    Invoke-ReleaseNotesStep $fixture 'v0.1.0-rc.2' $runnerTemp
    Assert-True ([IO.File]::ReadAllText($generatedPath) -ceq "`n`n$changelog") 'An empty curated file must not fail assembly or lose the changelog.'
}

Invoke-Case 'release without matching curated notes leaves generated bytes unchanged' {
    $fixture = New-Fixture
    $runnerTemp = Join-Path $fixture 'runner temp'
    New-Item -ItemType Directory -Path $runnerTemp | Out-Null
    $generatedPath = Join-Path $runnerTemp 'release-notes.md'
    $changelog = "## Generated only`r`n`r`nKeep these exact bytes.`r`n"
    [IO.File]::WriteAllText($generatedPath, $changelog, [Text.UTF8Encoding]::new($true))
    $before = (Get-FileHash -LiteralPath $generatedPath -Algorithm SHA256).Hash

    Invoke-ReleaseNotesStep $fixture 'v0.1.0-rc.2' $runnerTemp
    Assert-True ((Get-FileHash -LiteralPath $generatedPath -Algorithm SHA256).Hash -ceq $before) 'Absent notes directory must leave generated bytes unchanged.'

    $notesRoot = Join-Path $fixture 'docs/release-notes'
    New-Item -ItemType Directory -Path $notesRoot | Out-Null
    [IO.File]::WriteAllText((Join-Path $notesRoot 'v0.1.0-rc.1.md'), 'Only an older release has highlights')
    Invoke-ReleaseNotesStep $fixture 'v0.1.0-rc.2' $runnerTemp
    Assert-True ((Get-FileHash -LiteralPath $generatedPath -Algorithm SHA256).Hash -ceq $before) 'Notes for another tag must leave generated bytes unchanged.'
}
