import { expect, test } from "@playwright/test";
import { actions, capture, expectFiles, fixture, generateFf7Fixtures, manifest, openFf7, patch, preview, recordApi, snapshot, state, unchanged } from "./ff7-helpers";
import { exportFiles } from "./helpers";
import { contained, screenshot, tabTo } from "./unreal-helpers";

let directory: string;
test.use({ trace: "on", screenshot: "on" });
test.beforeAll(async ({ request }, testInfo) => { expect(request).toBeDefined(); directory = await generateFf7Fixtures(testInfo); });

test("FF7 preview cancel, one F6 history group, whole download and real UI reimport", async ({ page }, testInfo) => {
  const flush = recordApi(page, testInfo);
  const binary = await fixture(directory, "remake");
  const documentPath = await openFf7(page, binary);
  const panel = page.locator(".presets-panel");
  await panel.getByRole("combobox", { name: "Action", exact: true }).selectOption(actions.restock);
  const quantity = panel.getByRole("textbox", { name: "Target count", exact: true });
  await tabTo(page, quantity);
  await quantity.fill("99");
  await quantity.press("Tab");
  await capture(page, "FF7 full history");
  const before = await snapshot(page.request, documentPath);
  const first = await preview(page, "FF7 full history");
  expect(first.preview.plan.changes.map(change => change.valueId).sort()).toEqual(["inventory/0/quantity", "inventory/1/quantity", "inventory/200/quantity"]);
  const review = panel.locator(".presets-preview");
  await expect(review.getByRole("region", { name: "Preset preview changes and skipped rows" })).toBeVisible();
  await expect(review).toContainText("3 changes; revision 0.");
  await expect(review.getByRole("button", { name: "Apply preset", exact: true })).toBeEnabled();
  await unchanged(page.request, documentPath, before);
  await screenshot(page, testInfo, "ff7-real-preview");
  await page.keyboard.press("Escape");
  await expect(review).not.toBeVisible();
  await expect(panel.getByRole("listitem").filter({ hasText: "FF7 full history" }).getByRole("button", { name: "Preview", exact: true })).toBeFocused();
  await unchanged(page.request, documentPath, before);
  await preview(page, "FF7 full history");
  await tabTo(page, review.getByRole("button", { name: "Apply preset", exact: true }));
  const applying = page.waitForResponse(response => /\/presets\/[^/]+\/apply$/.test(response.url()));
  await page.keyboard.press("Enter");
  expect((await applying).status()).toBe(200);
  await expect(review).not.toBeVisible();
  await expect(page.getByRole("status").filter({ hasText: "Preset applied. Use Undo" })).toHaveCount(1);
  expect(await state(page.request, documentPath)).toMatchObject({ revision: 1, canUndo: true, canRedo: false });
  const expected = patch(binary, { "inventory/0/quantity": 99, "inventory/1/quantity": 99, "inventory/200/quantity": 99 });
  expectFiles((await snapshot(page.request, documentPath)).files, expected);
  await tabTo(page, page.getByRole("button", { name: "Undo", exact: true }));
  await page.keyboard.press("Enter");
  await expect(page.getByRole("button", { name: "Undo", exact: true })).toBeDisabled();
  expect(await state(page.request, documentPath)).toMatchObject({ revision: 2, canUndo: false, canRedo: true });
  expectFiles((await snapshot(page.request, documentPath)).files, binary.files);
  await tabTo(page, page.getByRole("button", { name: "Redo", exact: true }));
  await page.keyboard.press("Enter");
  await expect(page.getByRole("button", { name: "Undo", exact: true })).toBeEnabled();
  expect(await state(page.request, documentPath)).toMatchObject({ revision: 3, canUndo: true, canRedo: false });
  const downloaded = await exportFiles(page, testInfo, "ff7-edited-whole.zip");
  expectFiles(downloaded, expected);
  await manifest(testInfo, "ff7-original-members", binary.files);
  await manifest(testInfo, "ff7-downloaded-members", downloaded);
  const reopenedPath = await openFf7(page, { ...binary, files: downloaded });
  expectFiles((await snapshot(page.request, reopenedPath)).files, expected);
  await page.getByRole("tab", { name: "Inventory", exact: true }).click();
  const load = page.getByRole("button", { name: /^Load Inventory$/ });
  if (await load.isVisible()) await load.click();
  await expect(page.getByRole("table", { name: "Inventory", exact: true }).getByRole("row").nth(1).getByRole("textbox", { name: /^Quantity/ })).toHaveValue("99");
  const rows = page.getByRole("region", { name: "Inventory rows", exact: true });
  await contained(page, rows, 1280);
  const beforeScroll = await snapshot(page.request, reopenedPath);
  await page.getByRole("button", { name: "Show empty slots", exact: true }).click();
  await expect.poll(() => rows.evaluate(element => element.scrollHeight > element.clientHeight)).toBe(true);
  await tabTo(page, rows);
  await expect(rows).toBeFocused();
  await page.keyboard.press("PageDown");
  expect(await rows.evaluate(element => element.scrollTop)).toBeGreaterThan(0);
  await expect(rows).toBeFocused();
  await page.keyboard.press("Home");
  expect(await rows.evaluate(element => element.scrollTop)).toBe(0);
  await unchanged(page.request, reopenedPath, beforeScroll);
  await screenshot(page, testInfo, "ff7-real-reimported-quantity");
  await flush();
});
