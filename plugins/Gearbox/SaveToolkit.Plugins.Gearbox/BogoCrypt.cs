namespace SaveToolkit.Plugins.Gearbox;

/// <summary>Independent implementation of the 32-byte ciphertext-feedback XOR format.
/// Public PS4 mask facts: FromDarkHell/BL3SaveEditor, BL3Tools/Decryption (Rick/Gibbed).
/// The same two mask pairs are verified on both supplied PS5 titles.</summary>
internal static class BogoCrypt
{
    private const int Window = 32;
    private static ReadOnlySpan<byte> SavePrefix =>
        [0xD1, 0x7B, 0xBF, 0x75, 0x4C, 0xC1, 0x80, 0x30, 0x37, 0x92, 0xBD, 0xD0, 0x18, 0x3E, 0x4A, 0x5F,
         0x43, 0xA2, 0x46, 0xA0, 0xED, 0xDB, 0x2D, 0x9F, 0x56, 0x5F, 0x8B, 0x3D, 0x6E, 0x73, 0xE6, 0xB8];
    private static ReadOnlySpan<byte> SaveXor =>
        [0xFB, 0xFD, 0xFD, 0x51, 0x3A, 0x5C, 0xDB, 0x20, 0xBB, 0x5E, 0xC7, 0xAF, 0x66, 0x6F, 0xB6, 0x9A,
         0x9A, 0x52, 0x67, 0x0F, 0x19, 0x5D, 0xD3, 0x84, 0x15, 0x19, 0xC9, 0x4A, 0x79, 0x67, 0xDA, 0x6D];
    private static ReadOnlySpan<byte> ProfilePrefix =>
        [0xAD, 0x1E, 0x60, 0x4E, 0x42, 0x9E, 0xA9, 0x33, 0xB2, 0xF5, 0x01, 0xE1, 0x02, 0x4D, 0x08, 0x75,
         0xB1, 0xAD, 0x1A, 0x3D, 0xA1, 0x03, 0x6B, 0x1A, 0x17, 0xE6, 0xEC, 0x0F, 0x60, 0x8D, 0xB4, 0xF9];
    private static ReadOnlySpan<byte> ProfileXor =>
        [0xBA, 0x0E, 0x86, 0x1D, 0x58, 0xE1, 0x92, 0x21, 0x30, 0xD6, 0xCB, 0xF0, 0xD0, 0x82, 0xD5, 0x58,
         0x36, 0x12, 0xE1, 0xF6, 0x39, 0x44, 0x88, 0xEA, 0x4E, 0xFB, 0x04, 0x74, 0x07, 0x95, 0x3A, 0xA2];

    public static byte[] Decode(ReadOnlySpan<byte> ciphertext, bool profile)
    {
        var prefix = profile ? ProfilePrefix : SavePrefix;
        var xor = profile ? ProfileXor : SaveXor;
        var plaintext = new byte[ciphertext.Length];
        for (var i = 0; i < plaintext.Length; i++)
            plaintext[i] = (byte)(ciphertext[i] ^ (i < Window ? prefix[i] : ciphertext[i - Window]) ^ xor[i % Window]);
        return plaintext;
    }

    public static byte[] Encode(ReadOnlySpan<byte> plaintext, bool profile)
    {
        var prefix = profile ? ProfilePrefix : SavePrefix;
        var xor = profile ? ProfileXor : SaveXor;
        var ciphertext = new byte[plaintext.Length];
        for (var i = 0; i < ciphertext.Length; i++)
            ciphertext[i] = (byte)(plaintext[i] ^ (i < Window ? prefix[i] : ciphertext[i - Window]) ^ xor[i % Window]);
        return ciphertext;
    }
}
