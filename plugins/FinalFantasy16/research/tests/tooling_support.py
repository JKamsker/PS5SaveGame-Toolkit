"""Run only local tooling, with every write confined to a temporary plugin tree."""
import importlib.util
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile

RESEARCH = Path(__file__).resolve().parents[1]
PLUGIN = RESEARCH.parent
PACKS = PLUGIN / "SaveToolkit.Plugins.FinalFantasy16/ReferencePacks"
INPUTS = Path(__file__).resolve().parent / "inputs"
GOLDENS = Path(__file__).resolve().parent / "goldens"


def checkout_bytes(path):
    # Git checks these text artifacts out as CRLF on Windows. Their committed
    # format is UTF-8/LF. Never normalize the regenerated bytes being asserted.
    return path.read_bytes().replace(b"\r\n", b"\n")


def temporary_directory():
    root = os.environ.get("SAVETOOLKIT_TEST_TEMP")
    return tempfile.TemporaryDirectory(prefix="ffxvi-regeneration-", dir=root)


def copy_media_inputs(root):
    research = root / "research"
    research.mkdir(parents=True)
    for name in ("build_published_catalog.py", "build_ability_catalog.py",
                 "apply_game_assets.py", "round2-naming-audit.json", "game-assets.json"):
        shutil.copyfile(RESEARCH / name, research / name)
    shutil.copytree(RESEARCH / "published-ids", research / "published-ids")
    packs = root / "SaveToolkit.Plugins.FinalFantasy16/ReferencePacks"
    for name in ("ffxvi.published.en", "ffxvi.abilities.en", "ffxvi.maps.en"):
        shutil.copytree(PACKS / name, packs / name)
    return packs


def run_script(path, *args, artifacts=None):
    environment = os.environ.copy()
    if artifacts is not None:
        environment["SAVETOOLKIT_ARTIFACTS"] = str(artifacts)
    # Match the committed UTF-8/LF format even when stdout is a Windows pipe.
    bootstrap = ("import runpy,sys; sys.stdout.reconfigure(encoding='utf-8',newline='\\n'); "
                 "sys.argv=sys.argv[1:]; runpy.run_path(sys.argv[0],run_name='__main__')")
    return subprocess.run(
        [sys.executable, "-I", "-B", "-X", "utf8", "-c", bootstrap, str(path), *map(str, args)],
        stdin=subprocess.DEVNULL, capture_output=True, env=environment,
        timeout=120, check=False)


def load_tool(name):
    spec = importlib.util.spec_from_file_location(name, RESEARCH / (name + ".py"))
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module
