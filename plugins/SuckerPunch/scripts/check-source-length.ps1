param([switch]$Staged)
$ErrorActionPreference = 'Stop'
$warningLimit = 300
$hardLimit = 399
$pluginRoot = Split-Path $PSScriptRoot -Parent
$repositoryRoot = (git -C $pluginRoot rev-parse --show-toplevel).Trim()
$files = if ($Staged) {
    git -C $repositoryRoot diff --cached --name-only --diff-filter=ACMR -- 'plugins/SuckerPunch/**/*.cs'
} else {
    Get-ChildItem -LiteralPath $pluginRoot -Recurse -Filter '*.cs' |
        Where-Object FullName -NotMatch '[\\/](obj|bin)[\\/]' |
        ForEach-Object { [IO.Path]::GetRelativePath($repositoryRoot, $_.FullName).Replace('\', '/') }
}
$failed = $false
foreach ($path in $files) {
    $lines = if ($Staged) { @(git -C $repositoryRoot show ":$path") } else {
        @(Get-Content -LiteralPath (Join-Path $repositoryRoot $path))
    }
    if ($LASTEXITCODE -and $Staged) { throw "Cannot read staged source: $path" }
    if (($lines | Select-Object -First 5) -match '<auto-generated') { continue }
    if ($lines.Count -gt $hardLimit) {
        Write-Host "ERROR: ${path}: $($lines.Count) lines (maximum $hardLimit). Split by responsibility."
        $failed = $true
    } elseif ($lines.Count -gt $warningLimit) {
        Write-Warning "${path}: $($lines.Count) lines (recommended maximum $warningLimit)."
    }
}
if ($failed) { exit 1 }
Write-Host 'SuckerPunch source length check passed.'
